const r = require("express").Router();
const c = require("../controllers/device.controller");
const validate = require("../middleware/validate");
const { requireAuth } = require("../middleware/auth");
const { asyncHandler: a } = require("../utils/http");
r.use(requireAuth);
r.get("/", a(c.list));
r.post("/", validate(c.pairSchema), a(c.pair));
r.get("/:id", a(c.get));
r.delete("/:id", a(c.remove));
r.post("/:id/buzzer", a(c.testBuzzer));
module.exports = r;
